#!/usr/bin/env bash
# SC1: Stellar testnet setup for FlexiPay.
#
# Creates fresh fp- identities, issues our own test USDC, deploys and initialises payout_vault.
# Safe to re-run: existing identities, trustlines, the asset contract and the vault are reused.
#
# Writes two files next to this script:
#   testnet-ids.env   public addresses and contract ids (safe to commit, used by STELLAR.md)
#   .env.secrets      secret keys for the API host (git-ignored, never commit)
#
# Requires Stellar CLI 28 and the Rust toolchain from rust-toolchain.toml.
# Env overrides: FP_VAULT_FEE_BPS (default 100 = 1.0 %), FP_DEMO_MINT (stroops, default 10,000 USDC),
#                FP_REDEPLOY_VAULT=1 to deploy a new vault even if one exists.
set -euo pipefail

cd "$(dirname "$0")/../.."
OUT_DIR=scripts/testnet
NET=testnet
FEE_BPS=${FP_VAULT_FEE_BPS:-100}
MINT=${FP_DEMO_MINT:-100000000000}

command -v stellar >/dev/null || {
	echo "stellar CLI not found. Install Stellar CLI 28 (and run: source ~/.cargo/env)." >&2
	exit 1
}

log() { printf '\n== %s\n' "$*"; }

ensure_key() {
	if ! stellar keys public-key "$1" >/dev/null 2>&1; then
		stellar keys generate "$1" --network "$NET" --fund >/dev/null
	fi
	stellar keys public-key "$1"
}

log "Identities"
DEPLOYER=$(ensure_key fp-deployer)
ISSUER=$(ensure_key fp-issuer)
TREASURY=$(ensure_key fp-treasury)
PAYER=$(ensure_key fp-payer-demo)
RECIPIENT_A=$(ensure_key fp-recipient-a)
RECIPIENT_B=$(ensure_key fp-recipient-b)
printf '%-16s %s\n' deployer "$DEPLOYER" issuer "$ISSUER" treasury "$TREASURY" \
	payer-demo "$PAYER" recipient-a "$RECIPIENT_A" recipient-b "$RECIPIENT_B"

ASSET="USDC:$ISSUER"

log "Test USDC trustlines"
for k in fp-treasury fp-payer-demo fp-recipient-a fp-recipient-b; do
	stellar tx new change-trust --source-account "$k" --line "$ASSET" --network "$NET" >/dev/null
	echo "$k trusts $ASSET"
done

log "Test USDC asset contract"
USDC_ID=$(stellar contract id asset --asset "$ASSET" --network "$NET")
if ! stellar contract invoke --id "$USDC_ID" --source-account fp-deployer --network "$NET" -- \
	decimals >/dev/null 2>&1; then
	stellar contract asset deploy --asset "$ASSET" --source-account fp-issuer --network "$NET" \
		--alias fp-usdc >/dev/null
fi
stellar contract alias add fp-usdc --id "$USDC_ID" --network "$NET" --overwrite >/dev/null 2>&1 || true
echo "fp-usdc $USDC_ID"

log "Fund the demo payer"
balance() {
	stellar contract invoke --id "$USDC_ID" --source-account fp-deployer --network "$NET" --send no -- \
		balance --id "$1" | tr -d '"'
}
PAYER_BAL=$(balance "$PAYER")
if [ "$PAYER_BAL" -lt "$MINT" ]; then
	stellar tx new payment --source-account fp-issuer --destination "$PAYER" --asset "$ASSET" \
		--amount "$((MINT - PAYER_BAL))" --network "$NET" >/dev/null
fi
echo "payer-demo balance: $(balance "$PAYER") stroops"

log "Build and deploy payout_vault"
stellar contract build --package payout-vault >/dev/null
WASM=target/wasm32v1-none/release/payout_vault.wasm
VAULT_ID=$(stellar contract alias show fp-payout-vault --network "$NET" 2>/dev/null || true)
if [ -z "$VAULT_ID" ] || [ "${FP_REDEPLOY_VAULT:-0}" = 1 ]; then
	VAULT_ID=$(stellar contract deploy --wasm "$WASM" --source-account fp-deployer --network "$NET" \
		--alias fp-payout-vault)
	# init has no caller check; run it right after deploy and verify the config below
	stellar contract invoke --id "$VAULT_ID" --source-account fp-deployer --network "$NET" -- \
		init --token "$USDC_ID" --treasury "$TREASURY" --fee_bps "$FEE_BPS" >/dev/null
fi
echo "fp-payout-vault $VAULT_ID"

log "Verify vault config"
CONFIG=$(stellar contract invoke --id "$VAULT_ID" --source-account fp-deployer --network "$NET" --send no -- config)
echo "$CONFIG"
case "$CONFIG" in
*"$USDC_ID"*"$TREASURY"*) ;;
*)
	echo "Vault config does not match our token and treasury. Re-run with FP_REDEPLOY_VAULT=1." >&2
	exit 1
	;;
esac
FEE_ON_CHAIN=$(printf '%s' "$CONFIG" | tr -d '[] "' | awk -F, '{print $3}')

log "Write $OUT_DIR/testnet-ids.env"
cat >"$OUT_DIR/testnet-ids.env" <<EOF
# Generated by scripts/testnet/setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Public values only.
FP_STELLAR_NETWORK=testnet
FP_STELLAR_RPC_URL=https://soroban-testnet.stellar.org
FP_STELLAR_NETWORK_PASSPHRASE="Test SDF Network ; September 2015"
FP_USDC_ASSET=$ASSET
FP_USDC_CONTRACT_ID=$USDC_ID
FP_PAYOUT_VAULT_ID=$VAULT_ID
FP_VAULT_FEE_BPS=$FEE_ON_CHAIN
FP_TREASURY_ADDRESS=$TREASURY
FP_PAYER_DEMO_ADDRESS=$PAYER
FP_RECIPIENT_A_ADDRESS=$RECIPIENT_A
FP_RECIPIENT_B_ADDRESS=$RECIPIENT_B
EOF

log "Write $OUT_DIR/.env.secrets (git-ignored)"
umask 077
cat >"$OUT_DIR/.env.secrets" <<EOF
# Testnet only. Never commit. Copy into the API host's environment settings.
FP_DEPLOYER_SECRET=$(stellar keys secret fp-deployer)
FP_PAYER_DEMO_SECRET=$(stellar keys secret fp-payer-demo)
FP_RECIPIENT_A_SECRET=$(stellar keys secret fp-recipient-a)
FP_RECIPIENT_B_SECRET=$(stellar keys secret fp-recipient-b)
EOF
git check-ignore -q "$OUT_DIR/.env.secrets" || {
	echo "WARNING: $OUT_DIR/.env.secrets is not git-ignored" >&2
	exit 1
}

log "Done"
