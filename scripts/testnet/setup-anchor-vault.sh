#!/usr/bin/env bash
# E1: deploy an *isolated* second payout_vault whose token is the SDF reference-anchor
# USDC (issuer GBBD47…), not the baseline vault USDC (issuer GBBO6N…).
#
# Does NOT modify scripts/testnet/testnet-ids.env or the baseline vault alias.
# Writes only:
#   scripts/testnet/testnet-ids-anchor-vault.env   (public; safe to commit after fill-in)
#   scripts/testnet/.env.secrets-anchor-vault      (git-ignored secrets overlay)
#
# Requires Stellar CLI 28 + Rust toolchain. Testnet only. No mainnet.
#
# Env overrides:
#   FP_ANCHOR_USDC_ASSET   default USDC:GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5
#   FP_ANCHOR_VAULT_FEE_BPS default 100
#   FP_REDEPLOY_ANCHOR_VAULT=1  force a new deploy (changes the anchor vault id)
set -euo pipefail

cd "$(dirname "$0")/../.."
OUT_DIR=scripts/testnet
NET=testnet
FEE_BPS=${FP_ANCHOR_VAULT_FEE_BPS:-100}
ANCHOR_ASSET=${FP_ANCHOR_USDC_ASSET:-USDC:GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5}
HOME_DOMAIN=${FP_ANCHOR_HOME_DOMAIN:-testanchor.stellar.org}
ALIAS=fp-payout-vault-anchor

command -v stellar >/dev/null || {
	echo "stellar CLI not found. Install Stellar CLI 28." >&2
	exit 1
}

log() { printf '\n== %s\n' "$*"; }

# Reuse baseline identities (payer/treasury/deployer) from the existing key store.
# Do not rotate baseline secrets here.
for k in fp-deployer fp-treasury fp-payer-demo fp-recipient-a; do
	if ! stellar keys public-key "$k" >/dev/null 2>&1; then
		echo "missing stellar key $k — run scripts/testnet/setup.sh first for baseline identities." >&2
		exit 1
	fi
done

DEPLOYER=$(stellar keys public-key fp-deployer)
TREASURY=$(stellar keys public-key fp-treasury)
PAYER=$(stellar keys public-key fp-payer-demo)
RECIPIENT_A=$(stellar keys public-key fp-recipient-a)

log "Anchor USDC trustlines (classic) for payer + recipient A + treasury"
# Treasury must trust the vault token or claim fee transfer fails (Contract #13).
for k in fp-payer-demo fp-recipient-a fp-treasury; do
	stellar tx new change-trust --source-account "$k" --line "$ANCHOR_ASSET" --network "$NET" >/dev/null || true
	echo "$k trusts $ANCHOR_ASSET"
done

log "Anchor USDC Stellar Asset Contract id"
USDC_ID=$(stellar contract id asset --asset "$ANCHOR_ASSET" --network "$NET")
# Ensure the SAC exists on testnet (asset deploy is idempotent enough for SAC wrap).
if ! stellar contract invoke --id "$USDC_ID" --source-account fp-deployer --network "$NET" -- \
	decimals >/dev/null 2>&1; then
	# Issuer for GBBD47 is Circle's test issuer — we cannot re-issue; SAC wrap may already exist.
	echo "WARNING: could not simulate decimals() on $USDC_ID — confirm SAC on testnet before funding." >&2
fi
echo "anchor USDC SAC $USDC_ID"

log "Build payout_vault WASM (same package as baseline)"
# Prefer a stable local target dir so deploy can read the wasm path.
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$PWD/target}"
BUILD_OUT=$(stellar contract build --package payout-vault)
echo "$BUILD_OUT"
WASM="$CARGO_TARGET_DIR/wasm32v1-none/release/payout_vault.wasm"
if [ ! -f "$WASM" ]; then
	# stellar may print an optimized path under a temp cargo-target; recover it.
	WASM=$(printf '%s' "$BUILD_OUT" | sed -n 's/.*Wasm File: //p' | head -1 | tr -d '[:space:]')
fi
if [ ! -f "$WASM" ]; then
	echo "payout_vault.wasm not found after build" >&2
	exit 1
fi
echo "using wasm $WASM"

VAULT_ID=$(stellar contract alias show "$ALIAS" --network "$NET" 2>/dev/null || true)
if [ -z "$VAULT_ID" ] || [ "${FP_REDEPLOY_ANCHOR_VAULT:-0}" = 1 ]; then
	VAULT_ID=$(stellar contract deploy --wasm "$WASM" --source-account fp-deployer --network "$NET" \
		--alias "$ALIAS" -- \
		--token "$USDC_ID" --treasury "$TREASURY" --fee_bps "$FEE_BPS")
fi
echo "anchor vault $VAULT_ID (alias $ALIAS)"

log "Verify on-chain config matches this isolated env"
CONFIG=$(stellar contract invoke --id "$VAULT_ID" --source-account fp-deployer --network "$NET" --send no -- config)
echo "$CONFIG"
case "$CONFIG" in
*"$USDC_ID"*"$TREASURY"*) ;;
*)
	echo "Event vault config mismatch (token/treasury)." >&2
	exit 1
	;;
esac
FEE_ON_CHAIN=$(printf '%s' "$CONFIG" | tr -d '[] "' | awk -F, '{print $3}')

PASSPHRASE='Test SDF Network ; September 2015'

log "Write $OUT_DIR/testnet-ids-anchor-vault.env (public)"
GENERATED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
cat >"$OUT_DIR/testnet-ids-anchor-vault.env" <<EOF
# Generated by scripts/testnet/setup-anchor-vault.sh on ${GENERATED_AT}.
# Public values only. Does NOT replace testnet-ids.env (baseline vault).
FP_STELLAR_NETWORK=testnet
FP_STELLAR_RPC_URL=https://soroban-testnet.stellar.org
FP_STELLAR_NETWORK_PASSPHRASE="$PASSPHRASE"
FP_ANCHOR_HOME_DOMAIN=$HOME_DOMAIN
FP_ANCHOR_USDC_ASSET=$ANCHOR_ASSET
FP_ANCHOR_USDC_CONTRACT_ID=$USDC_ID
FP_ANCHOR_VAULT_ID=$VAULT_ID
FP_ANCHOR_VAULT_FEE_BPS=$FEE_ON_CHAIN
FP_ANCHOR_VAULT_TREASURY_ADDRESS=$TREASURY
# Demo addresses (same identities as baseline; trustlined for anchor USDC above)
FP_PAYER_DEMO_ADDRESS=$PAYER
FP_RECIPIENT_A_ADDRESS=$RECIPIENT_A
# Explicit non-baseline marker
FP_ANCHOR_VAULT_PURPOSE=reference-anchor-usdc-m1
EOF

log "Write $OUT_DIR/.env.secrets-anchor-vault (git-ignored overlay; same key names as baseline secrets)"
umask 077
cat >"$OUT_DIR/.env.secrets-anchor-vault" <<EOF
# Testnet only. Never commit. Overlay for M1 anchor vault — does not replace .env.secrets.
FP_DEPLOYER_SECRET=$(stellar keys secret fp-deployer)
FP_PAYER_DEMO_SECRET=$(stellar keys secret fp-payer-demo)
FP_RECIPIENT_A_SECRET=$(stellar keys secret fp-recipient-a)
EOF

log "Next (manual / API): SEP-24 deposit 1–10 of $ANCHOR_ASSET into the payer, then vault deposit into $VAULT_ID."
log "Baseline testnet-ids.env was not modified."
echo "PASS  anchor vault $VAULT_ID  token $USDC_ID  fee_bps $FEE_ON_CHAIN"
